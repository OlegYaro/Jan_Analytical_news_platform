/** Название страны для показа: при английском интерфейсе — английское, если имя не переименовано пользователем. */
export function countryDisplayName(code: string, name: string, lang: string = currentLang()): string {
  if (lang !== 'en') return name;
  const e = COUNTRY_NAMES[code.toUpperCase()];
  return e && e[0] === name ? e[1] : name;
}
